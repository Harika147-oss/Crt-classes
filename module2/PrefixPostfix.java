public class PrefixPostfix {
    public static void main(String[] args) {
        int a = 10;

        System.out.println("Initial value = " + a);

        System.out.println("Prefix (++a) = " + (++a));

        System.out.println("Postfix (a++) = " + (a++));

        System.out.println("Current value = " + a);
    }
}